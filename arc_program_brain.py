def apply_primitive(grid: np.ndarray, pid: int) -> np.ndarray:
    """Apply 1 of 8 ARC-style spatial/chromatic visual primitives to a (5, 5) int grid."""
    if pid == 0:
        return np.rot90(grid, k=-1)              # rot90 CW
    if pid == 1:
        return np.rot90(grid, k=2)               # rot180
    if pid == 2:
        return np.fliplr(grid)                   # flip_h
    if pid == 3:
        return np.flipud(grid)                   # flip_v
    if pid == 4:
        return np.roll(grid, shift=1, axis=1)    # shift_right
    if pid == 5:
        return np.roll(grid, shift=1, axis=0)    # shift_down
    if pid == 6:
        return (grid + 1) % N_COLORS             # color_shift(+1)
    return (N_COLORS - 1) - grid                 # color_invert


def apply_program(grid: np.ndarray, prog: tuple) -> np.ndarray:
    g = grid.copy()
    for p in prog:
        g = apply_primitive(g, p)
    return g


def build_primitive_matrices():
    """Exact linear 100x100 permutation matrices on one-hot (25x4) grids for fast vectorized 4-bit search."""
    mats = np.zeros((N_PRIMS, GRID_DIM, GRID_DIM), dtype=np.float32)
    for pid in range(N_PRIMS):
        for cell in range(N_CELLS):
            r, c = divmod(cell, GRID_W)
            # Track where pixel (r, c) with color col lands
            for col in range(N_COLORS):
                g_pos = np.full((GRID_H, GRID_W), -1, dtype=np.int64)
                g_pos[r, c] = 1
                if pid < 6:
                    # Pure spatial permutation
                    g_out = apply_primitive(g_pos, pid)
                    nr, nc = np.argwhere(g_out == 1)[0]
                    ncell = int(nr) * GRID_W + int(nc)
                    ncol = col
                else:
                    # Pure color permutation
                    ncell = cell
                    ncol = (col + 1) % N_COLORS if pid == 6 else (N_COLORS - 1 - col)
                mats[pid, ncell * N_COLORS + ncol, cell * N_COLORS + col] = 1.0
    return mats


