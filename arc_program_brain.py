def grid_to_onehot(g: np.ndarray) -> np.ndarray:
    flat = g.reshape(-1)
    oh = np.zeros((N_CELLS, N_COLORS), dtype=np.float32)
    oh[np.arange(N_CELLS), flat] = 1.0
    return oh.reshape(-1)


def sample_arc_task(split: str, rng):
    """Sample 1 ARC-style task: 3 demo pairs (X_k, Y_k), 1 test grid X_test, private human constraint c_human."""
    if split == "seen2":
        prog = SEEN_PAIRS[int(rng.integers(0, len(SEEN_PAIRS)))]
    elif split == "unseen2":
        prog = UNSEEN_PAIRS[int(rng.integers(0, len(UNSEEN_PAIRS)))]
    else:
        prog = UNSEEN_TRIPLES[int(rng.integers(0, len(UNSEEN_TRIPLES)))]

    demos_x = [rng.integers(0, N_COLORS, size=(GRID_H, GRID_W)) for _ in range(3)]
    demos_y = [apply_program(gx, prog) for gx in demos_x]
    test_x = rng.integers(0, N_COLORS, size=(GRID_H, GRID_W))
    pub_y = apply_program(test_x, prog)

    # Private embodied human domain constraint (0: direct, 1: color-complement) — invisible to Standalone AI!
    c_human = int(rng.integers(0, 2))
    true_y = pub_y if c_human == 0 else ((N_COLORS - 1) - pub_y)
    return {
        "prog": prog,
        "demos_x": demos_x,
        "demos_y": demos_y,
        "test_x": test_x,
        "pub_y": pub_y,
        "c_human": c_human,
        "true_y": true_y,
    }


def make_arc_batch(split: str, batch_size: int, rng):
    dx = np.zeros((batch_size, 3, GRID_DIM), dtype=np.float32)
    dy = np.zeros((batch_size, 3, GRID_DIM), dtype=np.float32)
    tx = np.zeros((batch_size, GRID_DIM), dtype=np.float32)
    ty = np.zeros((batch_size, N_CELLS), dtype=np.int64)
    ch = np.zeros(batch_size, dtype=np.int64)
    for b in range(batch_size):
        t = sample_arc_task(split, rng)
        for k in range(3):
            dx[b, k] = grid_to_onehot(t["demos_x"][k])
            dy[b, k] = grid_to_onehot(t["demos_y"][k])
        tx[b] = grid_to_onehot(t["test_x"])
        ty[b] = t["true_y"].reshape(-1)
        ch[b] = t["c_human"]
    return (
        torch.tensor(dx), torch.tensor(dy), torch.tensor(tx),
        torch.tensor(ch, dtype=torch.long), torch.tensor(ty, dtype=torch.long),
    )


