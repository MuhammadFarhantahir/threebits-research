# 2. Direct-Pixel Neural Transformer Baseline (~260k params, trained on 28 seen pairs)
# ---------------------------------------------------------------------------
class DirectPixelARCTransformer(nn.Module):
    """2-layer Transformer reading raw 5x5 demo grids directly (trained on 28 seen 2-step pairs, blind to private rule)."""

    def __init__(self, d_model=128, nhead=4):
        super().__init__()
        self.pair_proj = nn.Linear(2 * GRID_DIM, d_model)
        self.test_proj = nn.Linear(GRID_DIM, d_model)
        self.pos_emb = nn.Parameter(torch.randn(1, 4, d_model) * 0.04)
        enc_layer = nn.TransformerEncoderLayer(
            d_model=d_model, nhead=nhead, dim_feedforward=256, dropout=0.0,
            activation="gelu", batch_first=True,
        )
        self.encoder = nn.TransformerEncoder(enc_layer, num_layers=2)
        self.head = nn.Linear(d_model, GRID_DIM)

    def forward(self, dx, dy, tx):
        B = dx.shape[0]
        pairs = self.pair_proj(torch.cat([dx, dy], dim=-1))  # (B, 3, D)
        qtok = self.test_proj(tx).unsqueeze(1)               # (B, 1, D)
        seq = torch.cat([pairs, qtok], dim=1) + self.pos_emb
        out = self.encoder(seq)[:, -1, :]
        return self.head(out).view(B, N_CELLS, N_COLORS)


